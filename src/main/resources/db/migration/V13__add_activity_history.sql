-- Activity history (#12): append-only events written in the same transaction as the change.
-- The cascades only serve manual and test cleanup; the application never deletes projects or tasks.
CREATE TABLE activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    task_id BIGINT REFERENCES tasks(id) ON DELETE CASCADE,
    actor_account_id BIGINT NOT NULL REFERENCES accounts(id),
    resource_type VARCHAR(20) NOT NULL CHECK (resource_type IN ('PROJECT','TASK','MEMBER','COMMENT','LABEL')),
    resource_id BIGINT NOT NULL,
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATED','UPDATED','ARCHIVED','ADDED','REMOVED','DELETED')),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_activity_events_project ON activity_events(project_id, occurred_at DESC, id DESC);
CREATE INDEX idx_activity_events_task ON activity_events(task_id, occurred_at DESC, id DESC) WHERE task_id IS NOT NULL;

CREATE TABLE activity_changes (
    event_id BIGINT NOT NULL REFERENCES activity_events(id) ON DELETE CASCADE,
    position INT NOT NULL,
    field VARCHAR(40) NOT NULL,
    before_value TEXT,
    after_value TEXT,
    PRIMARY KEY (event_id, position)
);
