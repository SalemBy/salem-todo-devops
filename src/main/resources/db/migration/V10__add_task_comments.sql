-- Task comments (#11): plain text with a fixed author, soft-deleted through `active`.
-- The cascade from tasks only serves manual and test cleanup; the application never deletes tasks.
CREATE TABLE task_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    author_account_id BIGINT NOT NULL REFERENCES accounts(id),
    body VARCHAR(10000) NOT NULL CHECK (length(btrim(body)) > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_task_comments_task ON task_comments(task_id, id);
