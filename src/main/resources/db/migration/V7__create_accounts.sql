CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    display_name VARCHAR(100) NOT NULL CHECK (length(btrim(display_name)) > 0),
    password_hash VARCHAR(255) NOT NULL CHECK (length(password_hash) > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    credential_version BIGINT NOT NULL DEFAULT 0 CHECK (credential_version >= 0),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_accounts_email UNIQUE (email),
    CONSTRAINT ck_accounts_email_normalized CHECK (email = lower(btrim(email)) AND length(email) > 0)
);
