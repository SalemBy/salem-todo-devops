-- Requires an empty projects table (and therefore empty tasks, labels, and task_labels,
-- which all reference projects). Existing projects have no recorded creator, so no owner
-- can be assigned without guessing. This migration never deletes data.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM projects) THEN
        RAISE EXCEPTION 'V8 requires an empty projects table: existing projects have no recorded creator or owner. Reset the development database before upgrading.';
    END IF;
END
$$;

ALTER TABLE projects ADD COLUMN created_by_account_id BIGINT NOT NULL;
ALTER TABLE projects ADD CONSTRAINT fk_projects_created_by_account
    FOREIGN KEY (created_by_account_id) REFERENCES accounts(id);

CREATE TABLE project_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Projects are archived, never deleted by the application; the cascade only keeps
    -- memberships from outliving a project removed manually or by test cleanup.
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    role VARCHAR(20) NOT NULL CHECK (role IN ('OWNER', 'MEMBER', 'VIEWER')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_project_memberships_project_account UNIQUE (project_id, account_id)
);
CREATE INDEX idx_project_memberships_account ON project_memberships(account_id);
